#!/usr/bin/env python3
"""Refuse replacement and verify bytes downloaded through the GitHub API."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

from package import ASSETS, checksums, digest, validate_build_info
import tarfile
import zipfile


def gh(*args):
    return subprocess.check_output(['gh', *args], text=True)


def occupied_message(tag):
    return (f'A GitHub Release or tag named {tag} already exists.\n'
            'This workflow only owns the workflow-created draft after the build completes.\n'
            'Delete both the existing release and tag, or choose a new version.')


def api_get(path):
    """Return parsed JSON, or None on HTTP 404. Any other failure aborts (fail closed)."""
    result = subprocess.run(['gh', 'api', path], capture_output=True, text=True)
    if result.returncode != 0:
        if 'HTTP 404' not in result.stderr:
            raise RuntimeError(f'Cannot query {path}: {result.stderr}')
        return None
    try:
        return json.loads(result.stdout)
    except ValueError as error:
        raise RuntimeError(f'Cannot parse response for {path}: {error}') from error


def releases_for_tag(repo, tag):
    # Get-by-tag-name only resolves published releases; drafts need the list.
    try:
        pages = json.loads(gh('api', '--paginate', '--slurp', f'repos/{repo}/releases?per_page=100'))
    except (subprocess.CalledProcessError, ValueError) as error:
        raise RuntimeError(f'Cannot list releases for {repo}: {error}') from error
    return [release for page in pages for release in page if release.get('tag_name') == tag]


def is_empty(release):
    return not release.get('assets') and not (release.get('body') or '').strip()


def is_autogenerated_shell(repo, release):
    """A published release with no assets and only GitHub's own bare changelog.

    Publishing a tag from the Releases page without uploading artifacts leaves
    exactly this: no operator-written notes and nothing to preserve. Treat it
    like an empty placeholder. A release with any asset or hand-written notes
    is still a foreign release and must never be replaced.
    """
    if release.get('draft') or release.get('assets'):
        return False
    body = (release.get('body') or '').strip()
    pattern = rf'\*\*Full Changelog\*\*: https://github\.com/{re.escape(repo)}/compare/\S+'
    return re.fullmatch(pattern, body) is not None


def check_tag(repo, tag, commit):
    """A pre-existing tag is acceptable only when it points at the tested commit."""
    ref = api_get(f'repos/{repo}/git/ref/tags/{tag}')
    if ref is None:
        return
    obj = ref.get('object') or {}
    if obj.get('type') == 'tag':  # annotated: resolve to the tagged commit
        tagged = api_get(f'repos/{repo}/git/tags/{obj.get("sha")}')
        obj = (tagged or {}).get('object') or {}
    if obj.get('type') != 'commit' or not commit or obj.get('sha') != commit:
        raise RuntimeError(f'Tag {tag} already exists and does not point at the tested commit '
                           f'{commit or "(unknown)"}; refusing to move or recreate it.\n'
                           + occupied_message(tag))


def classify(repo, tag, commit):
    """Read-only classification of the release state for `tag`.

    Returns ('absent' | 'reuse-draft', placeholders). 'reuse-draft' means this
    workflow's own earlier draft with the expected assets: skip staging,
    `verify` still proves its bytes. Placeholders are releases with nothing to
    preserve that the caller may remove after all checks passed. Any other
    state fails closed with an actionable message. No GitHub writes here.
    """
    expected = {*ASSETS, 'SHA256SUMS'}
    existing = releases_for_tag(repo, tag)
    published = [r for r in existing if not r.get('draft')]
    drafts = [r for r in existing if r.get('draft')]
    placeholders = []
    for release in published:
        if not is_empty(release) and not is_autogenerated_shell(repo, release):
            raise RuntimeError(f'Release {repo}@{tag} is already published; refusing duplicate/replacement.\n'
                               + occupied_message(tag))
        placeholders.append(release)
    reuse = False
    if len(drafts) > 1:
        raise RuntimeError(f'Ambiguous draft releases for {repo}@{tag}: {len(drafts)} drafts; delete the extras.')
    if drafts:
        draft = drafts[0]
        names = {a['name'] for a in draft.get('assets') or []}
        if names == expected and all(a['size'] > 0 for a in draft['assets']) and len(draft['assets']) == 3:
            reuse = True
        elif is_empty(draft):
            placeholders.append(draft)
        else:
            raise RuntimeError(f'Draft release {repo}@{tag} has missing or unexpected assets '
                               f'({sorted(names) or "none"}); delete the draft and rerun.')
    check_tag(repo, tag, commit)
    return ('reuse-draft' if reuse else 'absent'), placeholders


def preflight(repo, tag, commit=None):
    """Classify, then remove placeholders before a new draft is staged."""
    state, placeholders = classify(repo, tag, commit)
    for release in placeholders:  # destructive steps only after every check passed
        release_id = release.get('id')
        if release_id is None:
            raise RuntimeError(f'Cannot identify empty release for {repo}@{tag}')
        gh('api', '-X', 'DELETE', f'repos/{repo}/releases/{release_id}')
        print(f'Removed empty placeholder release {repo}@{tag}; staging a verified draft')
    return state


def check(repo, tag, commit=None):
    """Fail fast without touching GitHub state (used before the costly builds)."""
    classify(repo, tag, commit)
    print(f'Release state for {repo}@{tag}: clear to build')


def find_release(repo, tag):
    # Get-by-tag-name only resolves published releases; drafts must come from
    # the paginated list so the staged draft can be verified before publication.
    pages = json.loads(gh('api', '--paginate', '--slurp', f'repos/{repo}/releases?per_page=100'))
    matches = [release for page in pages for release in page if release.get('tag_name') == tag]
    with_assets = [release for release in matches if release.get('assets')]
    candidates = with_assets or matches
    if not candidates:
        raise RuntimeError(f'No published or draft release exists for {repo}@{tag}')
    if len(candidates) != 1:
        raise RuntimeError(f'Ambiguous releases for {repo}@{tag}: {len(candidates)} candidates')
    return candidates[0]


def verify(repo, tag, directory):
    release = find_release(repo, tag)
    expected = {*ASSETS, 'SHA256SUMS'}
    assets = release['assets']
    if len(assets) != 3 or {a['name'] for a in assets} != expected or any(a['size'] <= 0 for a in assets):
        raise RuntimeError('Release must contain exactly both nonempty archives and SHA256SUMS')
    with tempfile.TemporaryDirectory() as temp:
        gh('release', 'download', tag, '--repo', repo, '--dir', temp)
        downloaded = Path(temp)
        checksums(downloaded, verify=True)
        checksums(directory, verify=True)
        for name in expected:
            if digest(downloaded / name) != digest(directory / name):
                raise RuntimeError(f'GitHub download differs from tested artifact: {name}')
        for name in ASSETS:
            archive = downloaded / name
            if name.endswith('.zip'):
                with zipfile.ZipFile(archive) as z:
                    info = json.loads(z.read('BUILD-INFO.json'))
            else:
                with tarfile.open(archive) as tar:
                    info = json.load(tar.extractfile('BUILD-INFO.json'))
            validate_build_info(info)
    print(f'Verified GitHub API assets and downloaded checksums for {repo}@{tag}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('operation', choices=['check', 'preflight', 'verify'])
    parser.add_argument('--directory', type=Path, default=Path('artifacts'))
    args = parser.parse_args()
    repo = os.environ['GITHUB_REPOSITORY']
    tag = os.environ.get('RELEASE_TAG') or os.environ['GITHUB_REF_NAME']
    commit = os.environ.get('RELEASE_COMMIT') or os.environ.get('GITHUB_SHA')
    if args.operation == 'check':
        check(repo, tag, commit)
    elif args.operation == 'preflight':
        state = preflight(repo, tag, commit)
        print(f'Release state for {repo}@{tag}: {state}')
        if os.environ.get('GITHUB_OUTPUT'):
            with open(os.environ['GITHUB_OUTPUT'], 'a') as out:
                out.write(f'reuse_draft={"true" if state == "reuse-draft" else "false"}\n')
    else:
        verify(repo, tag, args.directory)
